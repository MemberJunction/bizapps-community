export function GetArtifactWorldSeedSummary() {
  const counts = Object.fromEntries(
    Object.entries(WORLD_GROUPS).map(([key, rows]) => [key, rows.length]),
  );
  const totalRecords = Object.values(counts).reduce((sum, n) => sum + n, 0);
  const statuses = Array.from(
    new Set([
      ...WORLD_FORUM_ARTIFACT_POSTS.map((p) => p.Status),
      ...WORLD_FORUM_INTERACTIVE_POSTS.map((p) => p.Status),
      ...WORLD_FORUM_POST_REPLIES.map((r) => r.Status),
    ]),
  ).sort();
  const periods = Array.from(
    new Set([
      ...WORLD_FORUM_ARTIFACT_POSTS.map((p) => p.Period),
      ...WORLD_FORUM_INTERACTIVE_POSTS.map((p) => p.Period),
      ...WORLD_FORUM_POST_REPLIES.map((r) => r.Period),
    ]),
  ).sort();

  return {
    counts,
    totalRecords,
    categoryCount: Object.keys(counts).length,
    statuses,
    periods,
  };
}

export function BuildSeedDensityReport() {
  const summary = GetArtifactWorldSeedSummary();
  const passed = summary.totalRecords >= 20 && summary.categoryCount >= 10;
  return {
    schemaVersion: 'sf-readiness/v3',
    overallPassed: passed,
    pillars: {
      seedDensity: {
        passed,
        summary: `${summary.totalRecords} multi-entity domain-neutral seed records across ${summary.categoryCount} categories (${summary.statuses.length} statuses, ${summary.periods.length} quarters)`,
        checkedCount: summary.totalRecords,
        violationCount: passed ? 0 : 1,
        violations: passed ? [] : [`Expected >= 20 records, found ${summary.totalRecords}`],
        counts: summary.counts,
        statuses: summary.statuses,
        periods: summary.periods,
      },
    },
  };
}
