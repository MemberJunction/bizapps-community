// AC-EPIC-1 — Migration parity verification across both dialects + teardown parity.
//
// Both baseline migration files exceed 1 MB, so the GitHub `Read Repository File` tool used by
// the automated Reviewer/Validator returns empty content for them — this script is the substitute:
// it parses both files directly (and both teardown scripts), asserts the required structural
// parity, and writes a small, committed JSON evidence report the Validator CAN read directly.
//
//   node scripts/verify-migration-parity.mjs
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = join(HERE, '..');

const SQL_MIGRATION = join(REPO_ROOT, 'migrations', 'V202611060001__v0.1.x__Baseline_Tables_And_Access.sql');
const PG_MIGRATION = join(REPO_ROOT, 'migrations-pg', 'V202611060001__v0.1.x__Baseline_Tables_And_Access.pg.sql');
const SQL_TEARDOWN = join(REPO_ROOT, 'teardown', 'V1__Remove_Community_Schema.sql');
const PG_TEARDOWN = join(REPO_ROOT, 'teardown-pg', 'V1__Remove_Community_Schema.pg.sql');
const REPORT_PATH = join(REPO_ROOT, 'e2e', 'reports', 'migration-parity-report.json');
const VERIFY_FN_SQL = join(REPO_ROOT, 'scripts', 'verify-fn-community-forum-access.sql');

/** The 25 MJ_BizApps_Community base tables the baseline migration creates (and teardown drops). */
const EXPECTED_TABLES = [
  'CommunityMemberProfile', 'CommunitySpace', 'Forum', 'ForumAMAPost', 'ForumAnswerPost',
  'ForumArtifactPost', 'ForumCasePost', 'ForumFormPost', 'ForumIdeaAllocation', 'ForumIdeaCampaign',
  'ForumIdeaPost', 'ForumInteractivePost', 'ForumInteractiveSession', 'ForumMember', 'ForumPost',
  'ForumPostAttachment', 'ForumPostFlag', 'ForumPostReaction', 'ForumPostTag', 'ForumQuestionPost',
  'ForumRoleType', 'ForumSubscription', 'ForumTopicTag', 'ForumType', 'PostType',
].sort();

function sha256(content) {
  return createHash('sha256').update(content, 'utf8').digest('hex');
}

function extractTableNames(source, pattern) {
  const names = new Set();
  for (const match of source.matchAll(pattern)) {
    names.add(match[1]);
  }
  return Array.from(names).sort();
}

function arraysEqual(a, b) {
  return a.length === b.length && a.every((v, i) => v === b[i]);
}

/** Counts the longest run of CONSECUTIVE blank lines anywhere before the first CodeGen banner line. */
function maxBlankLinesBeforeCodeGenBanner(source) {
  const lines = source.split('\n');
  const bannerIndex = lines.findIndex((line) => line.includes('This was generated by the MemberJunction CodeGen tool'));
  if (bannerIndex === -1) return { bannerFound: false, maxConsecutiveBlankLines: 0 };

  let maxRun = 0;
  let currentRun = 0;
  for (let i = 0; i < bannerIndex; i++) {
    if (lines[i].trim() === '') {
      currentRun += 1;
      maxRun = Math.max(maxRun, currentRun);
    } else {
      currentRun = 0;
    }
  }
  return { bannerFound: true, maxConsecutiveBlankLines: maxRun };
}

function checkDialect(label, filePath, tableNamePattern) {
  const source = readFileSync(filePath, 'utf8');
  const violations = [];

  const tables = extractTableNames(source, tableNamePattern);
  if (!arraysEqual(tables, EXPECTED_TABLES)) {
    violations.push(
      `${label}: table inventory mismatch — expected ${EXPECTED_TABLES.length} tables [${EXPECTED_TABLES.join(', ')}], found ${tables.length} [${tables.join(', ')}]`,
    );
  }

  if (!/fnCommunityForumAccess/.test(source)) {
    violations.push(`${label}: no fnCommunityForumAccess definition found`);
  }

  const blankLines = maxBlankLinesBeforeCodeGenBanner(source);
  if (!blankLines.bannerFound) {
    violations.push(`${label}: no CodeGen banner ("This was generated by the MemberJunction CodeGen tool") found`);
  } else if (blankLines.maxConsecutiveBlankLines < 50) {
    violations.push(`${label}: only ${blankLines.maxConsecutiveBlankLines} consecutive blank lines before the CodeGen banner (requirement: >= 50)`);
  }

  const spDeleteUnneededEntityFieldsCount = (source.match(/spDeleteUnneededEntityFields/g) ?? []).length;
  if (spDeleteUnneededEntityFieldsCount > 0) {
    violations.push(`${label}: ${spDeleteUnneededEntityFieldsCount} spDeleteUnneededEntityFields call(s) found (requirement: zero)`);
  }

  if (filePath.endsWith('.pg.sql')) {
    if (/DECLARE\s+@|sys\.tables/i.test(source)) {
      violations.push(`${label}: untranslated T-SQL DECLARE @ / sys.tables artifact found in PostgreSQL migration`);
    }
    if (/"CASE"\s+"WHEN"/i.test(source)) {
      violations.push(`${label}: quoted SQL keywords ("CASE" "WHEN") found in PostgreSQL migration`);
    }
    if (!/CREATE FUNCTION __mj_BizAppsCommunity\."fnCommunityForumAccess"[\s\S]{0,200}RETURNS TABLE\s*\(/i.test(source)) {
      violations.push(`${label}: PostgreSQL fnCommunityForumAccess missing RETURNS TABLE (...) column signature`);
    }
    if (/INSERT INTO \$\{mjSchema\}\."EntityPermission"[\s\S]*?SELECT[^;]*?'Allow',\s*(?:0|1)\b/i.test(source)) {
      violations.push(`${label}: EntityPermission INSERT...SELECT passes integer (0/1) to BOOLEAN columns; must be true/false`);
    }
  }

  return {
    sha256: sha256(source),
    byteLength: Buffer.byteLength(source, 'utf8'),
    lineCount: source.split('\n').length,
    tableCount: tables.length,
    tables,
    fnCommunityForumAccessFound: /fnCommunityForumAccess/.test(source),
    maxConsecutiveBlankLinesBeforeCodeGen: blankLines.maxConsecutiveBlankLines,
    spDeleteUnneededEntityFieldsCount,
    violations,
  };
}

function checkTeardownParity() {
  const violations = [];

  const sqlSource = readFileSync(SQL_TEARDOWN, 'utf8');
  const sqlDroppedTables = extractTableNames(
    sqlSource,
    /DROP TABLE \[\$\{flyway:defaultSchema\}\]\.\[([A-Za-z]+)\]/g,
  );
  if (!arraysEqual(sqlDroppedTables, EXPECTED_TABLES)) {
    violations.push(
      `teardown (SQL Server): expected DROP TABLE statements for all 25 tables, found ${sqlDroppedTables.length} [${sqlDroppedTables.join(', ')}]`,
    );
  }

  const pgSource = readFileSync(PG_TEARDOWN, 'utf8');
  // PostgreSQL's teardown drops the whole schema CASCADE rather than enumerating each table —
  // that single statement is, by construction, complete parity with all 25 tables (and every
  // other object in the schema), so no per-table enumeration is expected here.
  const pgDropsSchemaCascade = /DROP SCHEMA IF EXISTS __mj_BizAppsCommunity CASCADE/.test(pgSource);
  if (!pgDropsSchemaCascade) {
    violations.push('teardown (PostgreSQL): expected "DROP SCHEMA IF EXISTS __mj_BizAppsCommunity CASCADE" — not found');
  }

  return {
    sqlServerDroppedTableCount: sqlDroppedTables.length,
    sqlServerDroppedTables: sqlDroppedTables,
    postgresDropsSchemaCascade: pgDropsSchemaCascade,
    violations,
  };
}

function checkVerifyFnScript() {
  const violations = [];
  let source = '';
  try {
    source = readFileSync(VERIFY_FN_SQL, 'utf8');
  } catch {
    violations.push(`${VERIFY_FN_SQL} not found`);
    return { throwAssertionCount: 0, violations };
  }

  const throwAssertionCount = (source.match(/THROW 50001/g) ?? []).length;
  if (throwAssertionCount < 4) {
    violations.push(`verify-fn-community-forum-access.sql: only ${throwAssertionCount} THROW 50001 assertion(s) found (expected >= 4: CanPost row, access isolation, row-count sanity, table inventory)`);
  }
  // A plain SELECT/PRINT with no THROW would exit 0 even on a wrong access row — the whole point
  // of this check is to prove the script actually asserts rather than just displaying output.
  const hasOnlySelectsNoThrow = /SELECT/.test(source) && !/THROW/.test(source);
  if (hasOnlySelectsNoThrow) {
    violations.push('verify-fn-community-forum-access.sql: contains SELECT statements but no THROW assertions — would exit 0 on wrong access rows');
  }

  return { throwAssertionCount, violations };
}

function main() {
  const sqlResult = checkDialect(
    'migrations/V202611060001__v0.1.x__Baseline_Tables_And_Access.sql',
    SQL_MIGRATION,
    /CREATE TABLE \[\$\{flyway:defaultSchema\}\]\.\[([A-Za-z]+)\]/g,
  );
  const pgResult = checkDialect(
    'migrations-pg/V202611060001__v0.1.x__Baseline_Tables_And_Access.pg.sql',
    PG_MIGRATION,
    /CREATE TABLE __mj_BizAppsCommunity\."([A-Za-z]+)"/g,
  );
  const teardownResult = checkTeardownParity();
  const verifyFnResult = checkVerifyFnScript();

  const allViolations = [...sqlResult.violations, ...pgResult.violations, ...teardownResult.violations, ...verifyFnResult.violations];
  const overallPassed = allViolations.length === 0;

  const report = {
    schemaVersion: 'sf-migration-parity/v1',
    evaluatedAtIso: new Date().toISOString(),
    overallPassed,
    expectedTableCount: EXPECTED_TABLES.length,
    sqlServerMigration: sqlResult,
    postgresMigration: pgResult,
    teardownParity: teardownResult,
    verifyFnCommunityForumAccessScript: verifyFnResult,
    violations: allViolations,
  };

  writeFileSync(REPORT_PATH, JSON.stringify(report, null, 2));
  const reportByteLength = Buffer.byteLength(JSON.stringify(report), 'utf8');

  if (!overallPassed) {
    console.error(allViolations.join('\n'));
    console.error(`${allViolations.length} migration parity violation(s) found. Report written to ${REPORT_PATH}.`);
    process.exitCode = 1;
    return;
  }
  console.log(
    `Migration parity verified: 25/25 tables in both dialects, fnCommunityForumAccess present in both, ` +
      `>= 50 consecutive blank lines before CodeGen in both, zero spDeleteUnneededEntityFields calls, ` +
      `25/25 teardown parity. Report (${reportByteLength} bytes) written to ${REPORT_PATH}.`,
  );
}

main();
